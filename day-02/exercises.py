# Día 02 · Variables
# Con = guardo el valor de la derecha en el nombre que escribí a la izquierda.

message = "Hello from Python!"  # Guardo un texto en la variable message.
study_minutes = 15  # Las palabras de un nombre de variable se pueden separar con _.
print(message)  # Escribo el nombre de la variable para mostrar el valor guardado.
print("Minutes =", study_minutes)  # Muestro un mensaje y el valor en la misma línea.

study_minutes = 20  # Reasigno la variable. A partir de acá, su valor es 20.
extra_minutes = 5  # Guardo un segundo valor para usarlo en la cuenta.
total_minutes = study_minutes + extra_minutes  # Sumo las dos variables y guardo el resultado.
print("Total minutes =", total_minutes)  # Puedo reutilizar el resultado de la cuenta.

galaxy_name = "Andromeda"  # Un nombre descriptivo me ayuda a recordar qué hay guardado.
print("Galaxy =", galaxy_name)  # Muestro el nombre que guardé en la variable.
