# Día 01 · Mi primer programa
# Uso # para dejarme una nota en el código. Python la salta al ejecutar.

print("Hello, world!")  # print() muestra en la terminal el texto que pongo entre comillas.
print("Hello,", "Laura!")  # Puedo pasar varios valores separados por comas. Se muestran con un espacio.
print()  # Deja una línea en blanco.

# Mis primeras cuentas
print("3 + 2")  # Las comillas hacen que se muestre la cuenta tal como está escrita.
print(3 + 2)  # Python calcula la suma y muestra 5.
print(9 - 4)  # Resto 4 a 9.
print(3 * 4)  # Uso * para multiplicar.
print(12 / 3)  # Uso / para dividir. El resultado se muestra como 4.0.

print(2 + 3 * 4)  # Primero se hace la multiplicación. El resultado es 14.
print((2 + 3) * 4)  # Los paréntesis hacen que la suma se resuelva primero. Da 20.

# Cuando algo falla, reviso que print esté en minúscula y que cierren las comillas y los paréntesis.
